// Hireclaw — minimal front end: in-browser key, task, signed answer, payment.
const state = {
  account: null, privateKey: null, fallback: false, task: null, shownAt: 0, busy: false,
  chain: null, earned: 0, withdrawing: false,
};

const $ = (id) => document.getElementById(id);
const hex = (buf) => [...new Uint8Array(buf)].map((b) => b.toString(16).padStart(2, "0")).join("");
const usdc = (n) => (n / 1e6).toFixed(2) + " USDC";
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

async function api(url, opts) {
  const res = await fetch(url, opts);
  return res.json();
}

function toast(text, bad = false) {
  const node = $("toast");
  node.textContent = text;
  node.className = "toast show" + (bad ? " bad" : "");
  clearTimeout(toast.timer);
  toast.timer = setTimeout(() => (node.className = "toast"), 2200);
}

const VIEWS = ["work", "boss", "ledger", "demo", "testnet", "code", "video"];

function currentView() {
  const found = VIEWS.find((name) => location.pathname.startsWith("/" + name));
  return found || "work";
}

// ------------------------------------------------------------------ identity
async function makeKey() {
  if (!crypto.subtle || !crypto.subtle.generateKey) return false;
  try {
    const pair = await crypto.subtle.generateKey({ name: "Ed25519" }, true, ["sign", "verify"]);
    const raw = await crypto.subtle.exportKey("raw", pair.publicKey);
    state.privateKey = pair.privateKey;
    state.account = hex(raw);
    return true;
  } catch (err) {
    return false;
  }
}

async function fallbackWorker() {
  const data = await api("/api/worker", { method: "POST", body: "{}" });
  state.account = data.account;
  state.fallback = true;
}

async function signPayload(payload) {
  const bytes = new TextEncoder().encode(JSON.stringify(payload));
  const signature = await crypto.subtle.sign({ name: "Ed25519" }, state.privateKey, bytes);
  return hex(signature);
}

// --------------------------------------------------------------------- work
async function workInit() {
  const local = await makeKey();
  if (!local) await fallbackWorker();
  $("withdraw-btn").onclick = withdraw;
  refreshChain();                    // never wait on the relay before showing the first task
  setInterval(refreshChain, 10000);
  $("identity").textContent =
    "implicit account " + state.account.slice(0, 24) + "…" +
    (state.fallback ? " — fallback key generated by the server (WebCrypto Ed25519 unavailable)" : " — key created in this browser");
  const snap = await api("/api/state");
  $("cap").textContent = usdc(snap.rules.worker_cap);
  await nextTask();
}

async function nextTask() {
  if (state.busy) return;
  state.busy = true;
  $("task-card").classList.add("hidden");
  $("idle-card").classList.remove("hidden");
  $("idle-text").textContent = "Looking for a task…";
  const card = await api(`/api/task?worker=${state.account}`);
  if (card.empty) {
    $("idle-text").textContent = "No task available right now: the bots are finishing the current job. A new one arrives in a few seconds.";
    state.busy = false;
    setTimeout(nextTask, 2500);
    return;
  }
  state.task = card;
  state.shownAt = performance.now();
  $("task-meta").textContent = `task ${card.task_id} · ${usdc(card.pay_usdc)} per validated answer`;
  $("task-text").textContent = card.text;
  const box = $("choices");
  box.innerHTML = "";
  card.choices.forEach((choice) => {
    const button = document.createElement("button");
    button.textContent = choice;
    button.onclick = () => submit(choice);
    box.appendChild(button);
  });
  $("idle-card").classList.add("hidden");
  $("task-card").classList.remove("hidden");
  state.busy = false;
}

async function submit(choice) {
  const card = state.task;
  if (!card) return;
  const latency = Math.round(performance.now() - state.shownAt);
  const payload = { choice, latency_ms: latency, task_id: card.task_id, worker: state.account };
  const body = { ...payload };
  if (!state.fallback) body.signature = await signPayload(payload);
  document.querySelectorAll("#choices button").forEach((b) => (b.disabled = true));
  const res = await api("/api/answer", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  if (res.retry) {
    state.task = null;
    setTimeout(nextTask, 400);
    return;
  }
  if (res.error) toast("Rejected: " + res.error, true);
  else if (res.task_status === "pay") toast(res.chain_tx ? "+ " + usdc(card.pay_usdc) + " — paid on-chain" : "+ " + usdc(card.pay_usdc));
  else if (res.task_status === "reject") toast("Rejected: " + res.reason, true);
  else toast("Waiting for other answers");
  if (res.chain_tx) showTx(res.chain_tx);
  if (res.worker) updateStats(res.worker);
  state.task = null;
  setTimeout(nextTask, 1000);
}

function showTx(tx) {
  const note = $("withdraw-note");
  note.classList.remove("hidden");
  note.innerHTML = `Latest on-chain payment: ${link("https://testnet.nearblocks.io/txns/" + esc(tx), tx.slice(0, 10) + "…")}`;
}

async function refreshChain() {
  const data = await api("/api/chain");
  state.chain = data;
  const line = $("chain-line");
  if (!data.available) {
    line.textContent = "Testnet relay unavailable: the demo runs locally (no real transaction).";
    $("withdraw-btn").classList.add("hidden");
    return;
  }
  const left = (Number(data.payroll_left || 0) / 1e6).toFixed(2);
  line.innerHTML = `Contract ${esc(data.contract)} · job ${esc(data.job || "—")} (${esc(data.job_state || "—")}) · ` +
    `payroll budget left ${left} USDC · ${link("https://testnet.nearblocks.io/address/" + esc(data.contract), "explorer")}`;
  const button = $("withdraw-btn");
  button.classList.toggle("hidden", state.earned <= 0);
}

async function withdraw() {
  if (state.withdrawing || !state.earned) return;
  state.withdrawing = true;
  $("withdraw-btn").disabled = true;
  const nonce = Date.now() % 1000000;
  const deadline = Date.now() + 120000;
  // The signed digest must match the contract's byte for byte:
  // sorted keys, amount as a number. The ticket sent carries the U128 as a string.
  const payload = { amount: Number(state.earned), deadline_ms: deadline, nonce, worker: state.account };
  const ticket = { worker: state.account, amount: String(state.earned), nonce, deadline_ms: deadline };
  if (!state.fallback) ticket.signature = await signPayload(payload);
  const res = await api("/api/withdraw", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ ticket }),
  });
  state.withdrawing = false;
  $("withdraw-btn").disabled = false;
  if (res.ok) {
    toast("Withdrawal relayed on-chain");
    showTx(res.tx || (res.txs || [])[0] || "");
    state.earned = 0;
    $("withdraw-btn").classList.add("hidden");
  } else {
    toast("Withdrawal rejected: " + (res.error || res.detail || "error"), true);
  }
}

function updateStats(worker) {
  state.earned = Number(worker.earned_today) || 0;
  $("earned").textContent = usdc(worker.earned_today);
  $("withdraw-btn").classList.toggle("hidden", !(state.earned > 0));
  $("paid").textContent = worker.tasks_paid;
  $("golds").textContent = worker.golds + (worker.golds ? ` (${worker.accuracy_pct}%)` : "");
}

// --------------------------------------------------------------------- boss
function cells(rows) {
  return rows.map(([label, value]) =>
    `<div class="cell"><span>${esc(label)}</span><strong>${value && value.__html ? value.__html : esc(value)}</strong></div>`).join("");
}

// a cell value that is already safe HTML (built with link())
function rawHtml(html) {
  return { __html: html };
}

async function renderBoss() {
  const snap = await api("/api/state");
  const job = snap.job;
  $("boss-head").innerHTML = cells([
    ["job", job.id],
    ["state", job.state],
    ["budget locked", usdc(job.budget)],
    ["payroll budget left", usdc(job.payroll_budget - job.payroll_spent)],
    ["payroll paid", usdc(job.payroll_spent)],
    ["margin reserved", usdc(job.margin_reserved)],
    ["rate per task", usdc(job.pay_per_task)],
    ["hidden checks", snap.rules.gold_pct + "%"],
  ]);
  const done = snap.progress.validated;
  const pct = Math.round((100 * done) / Math.max(1, snap.progress.total));
  $("progress-bar").style.width = pct + "%";
  $("progress-text").textContent = `${done}/${snap.progress.total} items validated (${pct}%) · ` +
    (snap.last_delivery ? `last delivery ${snap.last_delivery.correct}/${snap.last_delivery.total} correct` : "no delivery yet");

  $("workers").innerHTML =
    "<tr><th>Worker</th><th>Status</th><th>Paid</th><th>Rejected</th><th>Checks</th><th>Accuracy</th><th>Earned</th></tr>" +
    snap.workers.map((w) => `<tr><td class="mono">${esc(w.account.slice(0, 10))}…</td>
      <td><span class="tag ${esc(w.status)}">${esc(w.status)}</span></td>
      <td class="num">${w.tasks_paid}</td><td class="num">${w.tasks_rejected}</td>
      <td class="num">${w.golds}</td><td class="num">${w.accuracy_pct}%</td>
      <td class="num">${usdc(w.earned_total)}</td></tr>`).join("");

  const money = snap.ledger.filter((e) => ["payroll", "reject", "cost", "sale", "margin", "withdraw"].includes(e.kind)).slice(-12).reverse();
  $("payments").innerHTML =
    "<tr><th>#</th><th>Type</th><th>Amount</th><th>Detail</th></tr>" +
    money.map((e) => `<tr><td class="mono">${e.seq}</td><td>${esc(e.kind)}</td>
      <td class="num">${e.amount ? usdc(e.amount) : "—"}</td>
      <td>${esc(e.detail || e.reason)}</td></tr>`).join("");

  $("decisions").innerHTML = snap.decisions.slice(-8).reverse()
    .map((d) => `<li><strong>${esc(d.detail)}</strong> — ${esc(d.reason)}</li>`).join("");
}

// ------------------------------------------------------------------- ledger
async function renderLedger() {
  const snap = await api("/api/state");
  const rules = snap.rules;
  $("rules").innerHTML = cells([
    ["minimum pay", usdc(rules.pay_min)],
    ["cap per task", usdc(rules.pay_max)],
    ["min margin", rules.margin_pct + "%"],
    ["redundancy", rules.redundancy + " answers"],
    ["hidden checks", rules.gold_pct + "%"],
    ["worker cap/day", usdc(rules.worker_cap)],
    ["pay or reject", rules.pay_or_reject_s + " s"],
    ["pause", snap.paused ? "active" : "off"],
  ]);
  $("ledger").innerHTML =
    "<tr><th>#</th><th>Type</th><th>Actor</th><th>Amount</th><th>Detail</th></tr>" +
    snap.ledger.slice().reverse().map((e) => `<tr><td class="mono">${e.seq}</td>
      <td>${esc(e.kind)}</td><td class="mono">${esc(e.actor.slice(0, 10))}…</td>
      <td class="num">${e.amount ? usdc(e.amount) : "—"}</td>
      <td>${esc(e.detail || e.reason)}</td></tr>`).join("");
}

// ------------------------------------------------------------------ on-chain
async function renderChain() {
  const data = await api("/api/testnet");
  if (!data.available) {
    $("chain-note").textContent = "Testnet contract not deployed: " + (data.reason || "");
    return;
  }
  const sol = data.solvency || {};
  $("chain-note").innerHTML =
    `Contract <a class="mono" href="${esc(data.explorer)}" target="_blank" rel="noopener">${esc(data.contract)}</a> ` +
    `· token ${esc(data.token)} · deployed on ${esc((data.deployed_at || "").slice(0, 10))}`;
  $("chain").innerHTML = cells([
    ["USDC balance", usdc(Number(sol.balance || 0))],
    ["total liabilities", usdc(Number(sol.sum || 0))],
    ["invariant C-I1", sol.balanced ? "balanced" : "VIOLATED"],
    ["payroll locked", usdc(Number(sol.payroll_held || 0))],
    ["margins reserved", usdc(Number(sol.margins_held || 0))],
    ["owner", usdc(Number((sol.buckets || {}).owner || 0))],
    ["reserve", usdc(Number((sol.buckets || {}).reserve || 0))],
    ["contributors", usdc(Number((sol.buckets || {}).contributors || 0))],
  ]);
  const rows = Array.isArray(data.ledger) ? data.ledger.slice(-12).reverse() : [];
  $("chain-ledger").innerHTML =
    "<tr><th>#</th><th>Type</th><th>Amount</th><th>Detail</th></tr>" +
    rows.map((e) => `<tr><td class="mono">${e.seq}</td><td>${esc(e.kind)}</td>
      <td class="num">${Number(e.amount) ? usdc(Number(e.amount)) : "—"}</td>
      <td>${esc(e.detail || e.reason)}</td></tr>`).join("");
}

// ----------------------------------------------------------------------- init
function markNav() {
  const view = currentView();
  document.querySelectorAll("nav a").forEach((a) =>
    a.classList.toggle("active", a.dataset.view === view));
  document.querySelectorAll(".view").forEach((section) =>
    section.classList.toggle("hidden", section.id !== "view-" + view));
}

function handlerFor(view) {
  const extra = window.HIRECLAW_VIEWS || {};
  if (view === "work") return { render: workInit, every: 0 };
  if (view === "boss") return { render: renderBoss, every: 2000 };
  if (view === "ledger") return { render: () => Promise.all([renderLedger(), renderChain()]), every: 5000 };
  if (extra[view]) return { render: extra[view], every: view === "testnet" ? 15000 : 0 };
  return null;
}

document.addEventListener("DOMContentLoaded", async () => {
  markNav();
  const handler = handlerFor(currentView());
  if (!handler) return;
  await handler.render();
  if (handler.every) setInterval(handler.render, handler.every);
});